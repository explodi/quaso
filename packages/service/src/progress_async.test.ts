import { test } from "node:test";
import { openAsyncSqlite } from "./adapters/node_async_sqlite.ts";
import { PROGRESS_CASES } from "./testing/progress_cases.ts";
import { initializeUploadSql } from "./testing/upload_cases.ts";

for (const testCase of PROGRESS_CASES) {
  test(`async progress on SQLite: ${testCase.name}`, async () => {
    const opened = openAsyncSqlite(":memory:");
    try {
      await initializeUploadSql(opened.sql);
      await testCase.run(opened.sql);
    } finally {
      opened.close();
    }
  });
}
